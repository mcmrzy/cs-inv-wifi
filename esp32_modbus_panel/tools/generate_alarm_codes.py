"""Export raw alarm codes from the same names used by the Modbus LCD page."""
import argparse
import csv
import json
from pathlib import Path
import re

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--go-output',type=Path)
args=parser.parse_args()
text=(root/'main/panel_ui.c').read_text(encoding='utf-8')
names=[]
for name in ['faults','warnings']:
    block=re.search(r'const char \*const '+name+r'\[32\]=\{([^}]+)\}',text)
    values=re.findall(r'"([^"]+)"',block[1]);assert len(values)==32
    names.extend(values)

def read_3ku():
    from openpyxl import load_workbook

    workbook,=root.joinpath('docs').glob('*3KU*xlsx')
    book=load_workbook(workbook,read_only=True,data_only=True)
    try:
        words={}
        for row in book['WF_Simplify'].values:
            address=str(row[2]).strip() if len(row)>2 else ''
            if address not in ('0046','0047','0048','0049'):
                continue
            if address in words:
                raise ValueError(f'Duplicate 3KU alarm register {address}')
            bits={}
            for first,last,label in re.findall(r'BIT\((\d+)(?::(\d+))?\)\s*:\s*([^\r\n]+)',str(row[8])):
                first,last=int(first),int(last or first)
                name=label.split(' (',1)[0].strip()
                for bit in range(first,last+1):
                    if bit in bits:
                        raise ValueError(f'Duplicate 3KU alarm bit {address}:{bit}')
                    bits[bit]=name
            if set(bits)!=set(range(16)):
                raise ValueError(f'Incomplete 3KU alarm register {address}')
            words[address]=[bits[i] for i in range(16)]
        return [name for register in ('0046','0047','0048','0049') for name in words[register]]
    finally:
        book.close()

rows=[]
for base,labels in ((0x46,names),(0x56,read_3ku())):
    for index,name in enumerate(labels):
        register=0x46+index//16
        bit=index%16
        code=((base+index//16)<<8)|bit
        rows.append((code,0,2 if index<32 else 1,register,bit,name))
rows.extend((code,2,level,None,None,name) for code,level,name in (
    (0x4a00,2,'逆变器通信中断'),
    (0x4a01,1,'告警历史缺口（队列溢出）'),
    (0x4a02,1,'告警寄存器数据未知或过期'),
))
out=root/'docs/alarm_codes.csv';out.parent.mkdir(exist_ok=True)
with out.open('w',encoding='utf-8-sig',newline='') as f:
    w=csv.writer(f);w.writerow(['code_decimal','code_hex','source','level','register_hex','bit_0_based','name_zh'])
    for code,source,level,register,bit,name in rows:
        w.writerow([code,f'0x{code:04X}',source,level,f'0x{register:04X}' if register else '',bit,name])
if args.go_output:
    entries='\n'.join(f'\t0x{code:04x}: {json.dumps(name,ensure_ascii=False)},'
                      for code,_,_,_,_,name in sorted(rows))
    args.go_output.write_text(
        '// Code generated by esp32_modbus_panel/tools/generate_alarm_codes.py; DO NOT EDIT.\n'
        'package handler\n\nvar modbusPanelAlarmNames = map[int]string{\n'+entries+'\n}\n',
        encoding='utf-8')
print('PASS alarm codebook: 64 V1.27 bits, 64 3KU bits and 3 collector conditions')
