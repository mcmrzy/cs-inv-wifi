# -*- coding: utf-8 -*-
"""
gen_vectors.py — 生成 C 交叉验证测试向量 (test_vectors.h)

用 Python 参考实现 (protocol.py, 与 ARM 源码逐字节对齐) 生成一组
确定性的 (cmd, param1, param2, data, rand) → PPP 加密帧 向量,
供宿主测试 test_cs_protocol.c 验证 C 实现 (cs_protocol.c) 一致性。
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from protocol import send_frame  # noqa: E402


def gen_vectors():
    random.seed(20260730)
    cases = []

    # 1. 典型轮询: 读运行参数 0x03E8 176B (无数据)
    cases.append(dict(cmd=0x03, param1=0x03E8, param2=176, data=b'', rand=0x12345678, name='read_runparam'))
    # 2. 读只读信息 0x0190 52B
    cases.append(dict(cmd=0x06, param1=0x0190, param2=52, data=b'', rand=0x89ABCDEF, name='read_rdata'))
    # 3. 写控制参数 0x0001 2B (MaxChargeCurrentAll=30)
    cases.append(dict(cmd=0x02, param1=0x0001, param2=2, data=b'\x1e\x00', rand=0x00000000, name='write_ctrl'))
    # 4. 写 UTC 校时 0x00CA 4B
    cases.append(dict(cmd=0x05, param1=0x00CA, param2=4,
                      data=(0x6789ABCD).to_bytes(4, 'little'), rand=0xDEADBEEF, name='write_utc'))
    # 5. 读可读写 0x00C8 4B
    cases.append(dict(cmd=0x04, param1=0x00C8, param2=4, data=b'', rand=0x01020304, name='read_rw'))
    # 6. 读控制参数 0x0000 84B
    cases.append(dict(cmd=0x01, param1=0x0000, param2=84, data=b'', rand=0xCAFEBABE, name='read_ctrl'))
    # 7. 边界: 最小帧 param2=2
    cases.append(dict(cmd=0x03, param1=0x03E8, param2=2, data=b'', rand=0xFFFFFFFF, name='min_frame'))
    # 8. 随机帧 (含 0x7E/0x7D 转义字节)
    rnd = random.Random(7)
    data = bytes(rnd.randrange(256) for _ in range(64))
    cases.append(dict(cmd=0x02, param1=0x0028, param2=64, data=data, rand=0x55667788, name='random_esc'))
    # 9. 满 176B 数据写 (含转义)
    data2 = bytes(rnd.randrange(256) for _ in range(176))
    cases.append(dict(cmd=0x02, param1=0x0000, param2=176, data=data2, rand=0xA1B2C3D4, name='full_write'))
    # 10. 奇边界 param2=6 (CmdLen=16)
    cases.append(dict(cmd=0x02, param1=0x0010, param2=6, data=b'\x01\x02\x03\x04\x05\x06', rand=0x0F0F0F0F,
                      name='odd6'))

    out = []
    out.append('/* Auto-generated by gen_vectors.py — DO NOT EDIT */')
    out.append('#ifndef TEST_VECTORS_H')
    out.append('#define TEST_VECTORS_H')
    out.append('#include <stdint.h>')
    out.append('#include <stddef.h>')
    out.append('')
    out.append('typedef struct {')
    out.append('    const char *name;')
    out.append('    uint8_t  cmd;')
    out.append('    uint16_t param1;')
    out.append('    uint16_t param2;')
    out.append('    uint8_t  data[176];')
    out.append('    size_t   data_len;')
    out.append('    uint32_t rand;')
    out.append('    uint8_t  expect[420];')
    out.append('    size_t   expect_len;')
    out.append('} test_vector_t;')
    out.append('')
    out.append('static const test_vector_t g_vectors[] = {')

    for c in cases:
        fr = send_frame(c['cmd'], c['param1'], c['param2'], c['data'], c['rand'])
        assert len(fr) <= 420
        hexdata = ','.join('0x%02x' % b for b in c['data']) if c['data'] else ''
        hexexp = ','.join('0x%02x' % b for b in fr)
        out.append('    {')
        out.append('        .name = "%s",' % c['name'])
        out.append('        .cmd = 0x%02x,' % c['cmd'])
        out.append('        .param1 = 0x%04x,' % c['param1'])
        out.append('        .param2 = 0x%04x,' % c['param2'])
        out.append('        .data = {%s},' % hexdata)
        out.append('        .data_len = %d,' % len(c['data']))
        out.append('        .rand = 0x%08x,' % c['rand'])
        out.append('        .expect = {%s},' % hexexp)
        out.append('        .expect_len = %d,' % len(fr))
        out.append('    },')
    out.append('};')
    out.append('')
    out.append('#define VECTOR_COUNT (sizeof(g_vectors) / sizeof(g_vectors[0]))')
    out.append('')
    out.append('#endif /* TEST_VECTORS_H */')

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'test_vectors.h')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s (%d vectors)' % (path, len(cases)))


if __name__ == '__main__':
    gen_vectors()
