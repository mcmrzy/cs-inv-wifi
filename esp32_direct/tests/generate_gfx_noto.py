"""Static Noto SC Medium subset. Run at project root with Pillow and fontTools."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
import hashlib,json,math
root=Path(__file__).resolve().parents[1]
source=root/'tests/font-source/noto/NotoSansCJKsc-Medium.otf'
needed=set(range(32,127))
for p in (root/'main/direct').iterdir():
 if p.suffix in ('.c','.h','.inc') and 'assets' not in p.name:
  needed.update(ord(ch) for ch in p.read_text(encoding='utf-8') if 0x3000<=ord(ch)<=0xffff)
needed=sorted(needed)
fonts={n:ImageFont.truetype(str(source),n) for n in (12,14,16,24,28)}
cmap=TTFont(source).getBestCmap()
assert all(cp in cmap for cp in needed),'Required character missing'
out=['#include "direct_gfx_assets.h"','/* Noto Sans CJK SC Medium, SIL OFL 1.1. Generated by tests/generate_gfx_noto.py.', ' * 4bpp coverage, MS nibble first; native target sizes, static subset.', ' * Font SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+' */','typedef struct { uint32_t cp; direct_gfx_glyph_t glyph; } entry_t;']
byte_count=0;counts={}
def table(name,cps,px,cell,baseline):
 global byte_count
 entries=[]
 for cp in cps:
  ch=chr(cp);n=px;font=fonts[n]
  left,top,right,bottom=font.getbbox(ch,anchor='ls')
  base=baseline
  assert base+top>=0 and base+bottom<=cell,(hex(cp),n,(left,top,right,bottom),base,cell)
  advance=round(font.getlength(ch))
  if '0'<=ch<='9':advance=math.ceil(font.getlength('0'))
  x=max(0,-left);width=max(1,advance+x,right+x)
  im=Image.new('L',(width,cell));ImageDraw.Draw(im).text((x,base),ch,font=font,fill=255,anchor='ls')
  data=[];stride=(width+1)//2
  for y in range(cell):
   for xx in range(0,width,2):
    a=(im.getpixel((xx,y))*15+127)//255
    b=(im.getpixel((xx+1,y))*15+127)//255 if xx+1<width else 0
    data.append((a<<4)|b)
  symbol=f'{name}_{cp:x}'
  out.append(f'static const uint8_t {symbol}[]={{'+','.join(map(str,data))+'};')
  entries.append(f'{{0x{cp:x},{{{width},{cell},{stride},{advance},{symbol},4}}}}');byte_count+=len(data)
 out.append(f'static const entry_t {name}[]={{'+','.join(entries)+'};');counts[name]=len(entries)
table('body',needed,16,20,15)
# Generate complete numeric-unit runs, including spaces and SI prefixes.
nums=sorted(set(map(ord,'0123456789 .-+%VWAmkHzhdins')))
table('large24',nums,24,24,21)
table('large28',nums,28,28,24)
out+=['static const direct_gfx_glyph_t *lookup(const entry_t *t,unsigned n,uint32_t cp){unsigned l=0,r=n;while(l<r){unsigned m=l+(r-l)/2;if(t[m].cp<cp)l=m+1;else r=m;}return l<n && t[l].cp==cp?&t[l].glyph:0;}','#define FIND(t,cp) lookup(t,sizeof(t)/sizeof(t[0]),cp)','int direct_gfx_has_glyph(uint32_t cp){return FIND(body,cp)!=0;}','const direct_gfx_glyph_t *direct_gfx_glyph(uint32_t cp,int size){const direct_gfx_glyph_t *g=0;if(size==22 || size==24)g=FIND(large24,cp);else if(size==28)g=FIND(large28,cp);if(!g)g=FIND(body,cp);return g?g:FIND(body,63);}']
(root/'main/direct/direct_gfx_assets.c').write_text('\n'.join(out)+'\n',encoding='utf-8')
print(json.dumps({'glyph_tables':counts,'bitmap_bytes':byte_count,'font_sha256':hashlib.sha256(source.read_bytes()).hexdigest()}))
