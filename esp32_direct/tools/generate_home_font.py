"""Generate the isolated home-page Noto subset; does not change global fonts.

Requires Pillow. Run from any directory. The source's SIL OFL 1.1 license is
retained in tests/font-source/noto/LICENSE.txt. All glyphs are native size;
14px names receive a half-pixel stroke rendered offline at 4x resolution.
"""
from pathlib import Path
import hashlib
import json
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tests/font-source/noto/NotoSansCJKsc-Medium.otf'
DEST = ROOT / 'main/direct/direct_home_font.c'
CODEPOINTS = sorted(set(range(0x20, 0x7f)) | set(map(ord,
    '电网光伏电池负载充电放电待机数据过期未更新未知')))
OUT = ['#include "direct_home_font.h"', '#include "direct_gfx_assets.h"',
       '#include <stddef.h>', '#include <limits.h>',
       '/* Generated by tools/generate_home_font.py; Noto Sans CJK SC Medium, SIL OFL 1.1.',
       ' * Source SHA256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
       ' * 4bpp coverage, high nibble first; bearing offsets relative to baseline. */',
       'typedef struct { uint32_t cp; uint16_t offset; uint8_t width,height,stride,advance; int8_t xoff,yoff; } home_glyph_t;']
bitmap_bytes = 0
for size in (12, 14, 16):
    scale = 4 if size == 14 else 1
    stroke = 2 if size == 14 else 0
    font = ImageFont.truetype(str(SOURCE), size * scale)
    metrics_font = ImageFont.truetype(str(SOURCE), size)
    entries, data = [], []
    for cp in CODEPOINTS:
        char = chr(cp)
        left, top, right, bottom = font.getbbox(char, anchor='ls', stroke_width=stroke)
        left, top = math.floor(left / scale), math.floor(top / scale)
        right, bottom = math.ceil(right / scale), math.ceil(bottom / scale)
        width, height = max(1, right-left), max(1, bottom-top)
        advance = round(metrics_font.getlength(char))
        image = Image.new('L', (width * scale, height * scale))
        ImageDraw.Draw(image).text((-left*scale, -top*scale), char, font=font,
                                   anchor='ls', fill=255, stroke_width=stroke, stroke_fill=255)
        if scale != 1:
            image = image.resize((width, height), Image.Resampling.LANCZOS)
        stride = (width+1)//2
        offset = len(data)
        for row in range(height):
            for col in range(0, width, 2):
                a = (image.getpixel((col,row))*15+127)//255
                b = (image.getpixel((col+1,row))*15+127)//255 if col+1 < width else 0
                data.append((a<<4)|b)
        entries.append(f'{{0x{cp:x},{offset},{width},{height},{stride},{advance},{left},{top}}}')
    assert len(data) < 65536
    bitmap_bytes += len(data)
    OUT.append(f'static const uint8_t home_bitmap_{size}[]={{'+','.join(map(str,data))+'};')
    OUT.append(f'static const home_glyph_t home_glyphs_{size}[]={{'+','.join(entries)+'};')

OUT.append(r'''
static const home_glyph_t *find_glyph(uint32_t cp,int size,const uint8_t **bitmap)
{
 const home_glyph_t *table=home_glyphs_12;
 size_t count=sizeof(home_glyphs_12)/sizeof(home_glyphs_12[0]);
 *bitmap=home_bitmap_12;
 if(size==14){table=home_glyphs_14;*bitmap=home_bitmap_14;}
 else if(size==16){table=home_glyphs_16;*bitmap=home_bitmap_16;}
 size_t lo=0,hi=count;
 while(lo<hi){size_t mid=lo+(hi-lo)/2;if(table[mid].cp<cp)lo=mid+1;else hi=mid;}
 /* ASCII is contiguous at the beginning of every table. */
 return lo<count && table[lo].cp==cp?&table[lo]:&table['?'-' '];
}
int direct_home_text_width(const char *text,int size)
{
 if(!text)return 0;
 int width=0;
 while(*text){
  const uint8_t *bitmap;
  const home_glyph_t *glyph=find_glyph(direct_gfx_utf8_next(&text),size,&bitmap);
  if(width>INT_MAX-glyph->advance)return INT_MAX;
  width+=glyph->advance;
 }
 return width;
}
void direct_home_text(direct_gfx_t *g,int x,int baseline,const char *text,int size,uint16_t color)
{
 if(!g || !g->pixels || !text || g->width<=0 || g->height<=0)return;
 int64_t pen=x,clip_bottom=(int64_t)g->y0+g->height;
 while(*text){
  const uint8_t *bitmap;
  const home_glyph_t *glyph=find_glyph(direct_gfx_utf8_next(&text),size,&bitmap);
  int64_t left=pen+glyph->xoff,top=(int64_t)baseline+glyph->yoff;
  int64_t right=left+glyph->width,bottom=top+glyph->height;
  if(left<g->width && right>0 && top<clip_bottom && bottom>g->y0){
   int start_x=left<0?(int)-left:0;
   int end_x=right>g->width?(int)(g->width-left):glyph->width;
   int start_y=top<g->y0?(int)(g->y0-top):0;
   int end_y=bottom>clip_bottom?(int)(clip_bottom-top):glyph->height;
   const uint8_t *data=bitmap+glyph->offset;
   for(int row=start_y;row<end_y;row++)for(int col=start_x;col<end_x;col++){
    unsigned packed=data[row*glyph->stride+col/2];
    unsigned alpha=(col&1)?packed&15:packed>>4;
    if(!alpha)continue;
    size_t at=(size_t)(top+row-g->y0)*(size_t)g->width+(size_t)(left+col);
    if(alpha==15)g->pixels[at]=color;
    else{
     unsigned bg=g->pixels[at],inverse=15-alpha;
     unsigned red=(((color>>11)&31)*alpha+((bg>>11)&31)*inverse+7)/15;
     unsigned green=(((color>>5)&63)*alpha+((bg>>5)&63)*inverse+7)/15;
     unsigned blue=((color&31)*alpha+(bg&31)*inverse+7)/15;
     g->pixels[at]=(uint16_t)((red<<11)|(green<<5)|blue);
    }
   }
  }
  pen+=glyph->advance;
  if(pen>INT_MAX)break;
 }
}
''')
DEST.write_text('\n'.join(OUT)+'\n', encoding='utf-8')
print(json.dumps({'glyphs_per_size': len(CODEPOINTS), 'bitmap_bytes': bitmap_bytes,
                  'metadata_bytes': len(CODEPOINTS)*3*12,
                  'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest()}))
