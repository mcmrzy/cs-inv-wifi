const char *direct_alarm_message(direct_alarm_kind_t kind, unsigned index)
{
    const char *const *table = NULL;
    size_t count = 0;
    switch (kind) {
    case DIRECT_ALARM_BMS: table = BMSAlarmStr; count = sizeof(BMSAlarmStr) / sizeof(BMSAlarmStr[0]); break;
    case DIRECT_ALARM_WARNING: table = WarnStr; count = sizeof(WarnStr) / sizeof(WarnStr[0]); break;
    case DIRECT_ALARM_FAULT: table = FaultStr; count = sizeof(FaultStr) / sizeof(FaultStr[0]); break;
    default: return NULL;
    }
    return index < count ? table[index] : NULL;
}
